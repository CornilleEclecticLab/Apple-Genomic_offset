#!/usr/bin/env python3

import datetime
import sys
import textwrap
import os
start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')



version = "1.0.0"
script_basename = os.path.splitext(os.path.basename(sys.argv[0]))[0]
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
bin_dir = script_path
work_dir = os.path.dirname(script_path)
input_dir = os.path.join(work_dir,'in')
Project="dom_admixed_rm_by_ind"
output_dir = os.path.join(work_dir, 'out', Project, "s01.Stacks_by_chromosome")
sbatch_dir = os.path.join(work_dir, 'out', Project,"s00.sbatch")
sub_script_dir = os.path.join(bin_dir,script_basename+"_"+Project)

########################################################################
# Set input files
########################################################################
chr_vcf_list = os.path.join(input_dir,f'vcf_file_{Project}.txt')
chr_list = os.path.join(input_dir,f'chromosome_list.txt')
pop_path = os.path.join(input_dir,f'group_geo_{Project}.txt')

# Ensure output directory exists
os.makedirs(output_dir, exist_ok=True)
os.makedirs(sbatch_dir, exist_ok=True)
os.makedirs(sub_script_dir, exist_ok=True)

# Read chromosome ID as a list
with open(chr_list,'r') as file:
    chr_list = file.read().strip().split()

# Read VCF file path as a list
with open(chr_vcf_list,'r') as file:
    chr_vcf_list = file.read().strip().split()

# Generate pixy slurm script for every chromosome
for chr, vcf in zip(chr_list, chr_vcf_list):
    print(f'Generating slurm script for chromosome {chr} ...')
    if chr not in vcf:
        raise ValueError(
            f'Chromosome ID {chr} does not match VCF file name {vcf}')

    sub_script_prefix = script_basename+'.'+chr
    slurm_content = f'''#!/usr/bin/env bash
# This script was generated by {script_basename} v{version},
# at {start_time:%Y-%m-%d %H:%M:%S}

#SBATCH -J {sub_script_prefix}
#SBATCH --output=./out/{Project}/s00.sbatch/{sub_script_prefix}.out
#SBATCH --error=./out/{Project}/s00.sbatch/{sub_script_prefix}.err
#SBATCH --time=48:00:00
#SBATCH -c 10
#SBATCH --mem=400G

# Set up environment
module load all gencore/3
module load stacks

populations -V {vcf} -M {pop_path} -O {output_dir} --fstats

# populations -V {vcf} \
#             -M ./in/group_geo_full_genome_dom_admixed_rm_pi_by_ind.txt \
#             -O {output_dir} \
#             -p 1 \
#             -r 1.0 \
#             --hwe \
#             --no-hap-exports
'''
    # Write slurm script to file
    file = open(os.path.join(sub_script_dir,sub_script_prefix+'.sh'),'w')
    file.write(slurm_content)
    file.close()

# List all sub-scripts
files = [f for f in os.listdir(sub_script_dir) if os.path.isfile(os.path.join(sub_script_dir, f))]
output_file = os.path.join("./bin", f"list_split_sbatch_jobs_{Project}.txt")

with open(output_file, "w") as f:
    for file in files:
        f.write(f"sbatch {os.path.join(sub_script_dir, file)}\n")

print(f"Written sbatch commands to: {output_file}")


end_time = datetime.datetime.now()
print('')
print(' END '.center(79,'='))
print(str(end_time-start_time).center(79))

