#!/usr/bin/env python3

import datetime
import sys
import textwrap
import os

start_time = datetime.datetime.now()
print(f'{" Start ":=^79}')

version = "1.0.0"
script_basename = os.path.splitext(os.path.basename(sys.argv[0]))[0]
script_path = os.path.dirname(os.path.realpath(sys.argv[0]))
bin_dir = script_path
work_dir = os.path.dirname(script_path)
input_dir = os.path.join(work_dir, 'in')
Project = "all_wild"
output_dir = os.path.join(work_dir, 'out', Project, "s01.split_vcf_by_chr")
sub_script_dir = os.path.join(bin_dir, f"{script_basename}_{Project}")
#in_vcf = f"./out/{Project}/s01.filter_vcf/chr_concat.geno20_maf005.anno_filtered_{Project}.vcf.gz"
in_vcf = f"/scratch/mc10739/02-Wild_apple_genomic_offset/Apple-Genomic_offset/01-Population_structure/03-membership_coefficient_investigating/out/All_data_wo_orientalis/s04.5.filter_crops_ind/chr_concat.geno20_maf005.anno_all_wild.vcf.gz"
# Ensure directories exist
os.makedirs(output_dir, exist_ok=True)
os.makedirs(sub_script_dir, exist_ok=True)
os.makedirs("./bin", exist_ok=True)

def wrap79(text, width=79):
    return textwrap.fill(text, width=width, subsequent_indent=' ' * 4)

# Read chromosome list
with open(os.path.join(input_dir, 'chromosome_list.txt'), 'r') as fi:
    chr_list = fi.read().strip().split('\n')

# Header for each sub-script
header = f"""#!/usr/bin/env bash
# This script was generated by ../{script_basename}.py
# at {start_time}
# v{version}
"""

for chr in chr_list:
    sub_script_base = f"{script_basename}.{chr}"
    out_vcf = os.path.join(output_dir, f"chr_{chr}.geno20_maf005.anno_{Project}.vcf.gz")
    script_path = os.path.join(sub_script_dir, sub_script_base + '.sh')
    with open(script_path, 'w') as fo:
        fo.write(header)
        fo.write(f"""
#SBATCH -J {sub_script_base}
#SBATCH -o out/s00.sbatch/{sub_script_base}.out
#SBATCH -e out/s00.sbatch/{sub_script_base}.err
#SBATCH -c 4
#SBATCH --mem=8G

module load all gencore/3
module load samtools
module load bcftools

bcftools view \\
    {in_vcf} \\
    -r {chr} \\
    --threads 4 \\
    -O z \\
    -o {out_vcf}

tabix -p vcf {out_vcf}
""")

# List all sub-scripts
files = [f for f in os.listdir(sub_script_dir) if os.path.isfile(os.path.join(sub_script_dir, f))]
output_file = os.path.join("./bin", f"list_split_sbatch_jobs_{Project}.txt")

with open(output_file, "w") as f:
    for file in files:
        f.write(f"sbatch {os.path.join(sub_script_dir, file)}\n")

print(f"Written sbatch commands to: {output_file}")

end_time = datetime.datetime.now()
print('')
print(' END '.center(79, '='))
print(str(end_time - start_time).center(79))
